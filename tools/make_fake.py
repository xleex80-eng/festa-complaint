"""시험용 가짜 대장 2개를 만든다. 모든 성명·연락처·내용은 지어낸 값이다."""
import sys
from datetime import datetime
from pathlib import Path

import openpyxl

out = Path(sys.argv[1])
out.mkdir(parents=True, exist_ok=True)

# 시설불편: 건축 3, 기계 4(실험동 1), 전기 2, 통신 1, 승강기 0 = 10건 (처리중 1건, 카카오톡 1건)
SHEETS = ["미처리현황", "건축", "기계", "전기", "통신", "승강기"]
wb = openpyxl.Workbook()
wb.active.title = "통계"
ROWS = {
    "건축": [("창호", "창문", "창문이 안 닫힘", "청사동", "전화", "완료", 0), ("내장재", "벽", "벽 페인트 벗겨짐", "청사동", "IBS", "완료", 1), ("창호", "출입문", "출입문 고장", "청사동", "하모니", "처리중", None)],
    "기계": [("위생", "수전", "수전 물샘", "청사동", "전화", "완료", 0), ("위생", "비데", "비데 고장", "청사동", "전화", "완료", 5), ("위생", "대소변기", "변기 막힘", "실험동", "홈페이지", "완료", 0), ("냉난방", "난방", "난방 안 됨", "청사동", "카카오톡", "완료", 3)],
    "전기": [("전등", "점등불량", "전등 안 켜짐", "청사동", "전화", "완료", 0), ("전등", "스위치불량", "스위치 고장", "기타", "기타", "완료", 0)],
    "통신": [("행정통신", "전화", "전화기 고장", "청사동", "전화", "완료", 0)],
}
n = 100
for s in SHEETS:
    ws = wb.create_sheet(f"관리대장({s})")
    ws["B1"] = f"시설불편민원 관리대장({s})"
    ws["H3"] = "불편민원내용"
    ws["N3"] = "처리여부"
    ws["B5"] = "□ 처리중"
    ws["D5"] = "=COUNTIF(N6:N2999,\"처리중\")"
    ws["H5"] = "안내 문구(건수에 넣지 않음)"
    for i, (m, sm, text, bld, ch, st, days) in enumerate(ROWS.get(s, [])):
        r = 6 + i
        n += 1
        vals = {"B": f"민A{n:06d}", "C": 2026, "D": 10, "E": 5 + i, "F": 9, "G": f"{i:02d}", "H": text, "I": "테스트 조치", "J": "가상기관", "K": f"홍길동{n}", "L": f"010-0000-{n:04d}",
                "M": ch, "N": st, "O": "○○", "P": bld, "Q": s, "R": m, "S": sm, "T": "보수", "U": "고장", "V": "접수자가", "W": "처리자나", "X": None}
        if days is not None:
            vals.update({"Y": 2026, "Z": 10, "AA": 5 + i + days, "AB": 15, "AC": None if i == 0 else 30, "AD": "당일", "AE": 5})
        for c, v in vals.items():
            ws[f"{c}{r}"] = v
wb.save(out / "가짜_시설불편민원_관리대장.xlsx")

# 시설 외: 정상 5건 + 표기 오류 5건 + 번호만 있는 행 2개
